#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const base = String(process.env.WORKSPACE_FUNCTIONS_BASE || '').replace(/\/+$/, '');

if (!/^https:\/\/[-a-z0-9]+\.cloudfunctions\.net$/i.test(base)) {
  throw new Error('WORKSPACE_FUNCTIONS_BASE must be an HTTPS Cloud Functions base URL');
}

const target = path.resolve(__dirname, '..', 'runtime-config.js');
fs.writeFileSync(target, `// Generated by the release workflow. Contains no secrets.\nwindow.FUNCTIONS_BASE_URL = ${JSON.stringify(base)};\n`);
